// Generates packages/ui/src/icons.generated.ts from Material Symbols SVGs
// (Apache 2.0). Add a name to ICONS and re-run: node tools/gen-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const ICONS = [
  '3d_rotation', 'accessibility_new', 'add', 'arrow_back', 'backup', 'body_system', 'bug_report', 'category',
  'center_focus_strong', 'check', 'close', 'dark_mode', 'delete', 'deployed_code', 'download', 'edit',
  'female', 'folder_open', 'grid_on', 'info', 'install_desktop', 'layers', 'library_books', 'light_mode',
  'lightbulb', 'lock', 'lock_open', 'male', 'memory', 'menu', 'more_vert', 'movie', 'open_with', 'palette', 'pan_tool_alt', 'pause',
  'person', 'person_add', 'photo_camera', 'play_arrow', 'redo', 'restart_alt', 'science', 'search',
  'settings', 'shield_lock', 'speed', 'storage', 'straighten', 'tab', 'undo', 'upload', 'visibility',
  'visibility_off', 'warning', 'wb_sunny',
];

const require = createRequire(join(process.cwd(), 'packages/ui/package.json'));
const root = dirname(require.resolve('@material-symbols/svg-400/package.json'));

const lines = [];
for (const name of ICONS) {
  const svg = readFileSync(join(root, 'outlined', `${name}.svg`), 'utf8');
  const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]);
  if (!paths.length) throw new Error(`No path in ${name}`);
  lines.push(`  ${JSON.stringify(name)}: ${JSON.stringify(paths.join(' '))},`);
}

writeFileSync(
  'packages/ui/src/icons.generated.ts',
  `// Generated by tools/gen-icons.mjs from Material Symbols (Apache License 2.0). Do not edit.\n` +
    `// viewBox: 0 -960 960 960\n` +
    `export const ICON_PATHS = {\n${lines.join('\n')}\n} as const;\n`,
);
console.log(`Wrote ${ICONS.length} icons`);
